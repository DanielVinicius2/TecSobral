-- ---------------------------------------------------------------------
-- CATEGORIA
-- ---------------------------------------------------------------------
CREATE TABLE categoria (
    id_categoria  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(60) NOT NULL,
    CONSTRAINT uk_categoria_nome UNIQUE (nome),
    CONSTRAINT ck_categoria_nome CHECK (btrim(nome) <> '')
);

-- ---------------------------------------------------------------------
-- USUARIO  (RF01, RF02, RNF01, RNF02, RN14, RN16)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    id_usuario    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    login         VARCHAR(40)  NOT NULL,
    senha_hash    VARCHAR(255) NOT NULL,            -- nunca guardar senha em texto puro
    perfil        VARCHAR(20)  NOT NULL,
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE, -- RN16: desativa, não exclui
    data_criacao  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_login UNIQUE (login),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('PROPRIETARIO', 'FUNCIONARIO')),
    CONSTRAINT ck_usuario_nome CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_usuario_login CHECK (btrim(login) <> '')
);

-- ---------------------------------------------------------------------
-- PRODUTO  (RF03 a RF07, RN06, RN08, RN15)
-- quantidade_atual PODE ser negativa (RN04); estoque_minimo é opcional (RN06)
-- ---------------------------------------------------------------------
CREATE TABLE produto (
    id_produto              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                  VARCHAR(30)    NOT NULL,
    nome                    VARCHAR(120)   NOT NULL,
    id_categoria            INTEGER        NOT NULL,
    cor                     VARCHAR(40),
    tamanho                 VARCHAR(20),
    outras_caracteristicas  VARCHAR(255),
    quantidade_atual        INTEGER        NOT NULL DEFAULT 0,
    preco_compra            NUMERIC(10,2)  NOT NULL,
    preco_venda             NUMERIC(10,2)  NOT NULL,
    estoque_minimo          INTEGER,
    data_cadastro           TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_produto_codigo UNIQUE (codigo),
    CONSTRAINT fk_produto_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria (id_categoria) ON DELETE RESTRICT,
    CONSTRAINT ck_produto_codigo CHECK (btrim(codigo) <> ''),
    CONSTRAINT ck_produto_nome CHECK (btrim(nome) <> ''),
    CONSTRAINT ck_produto_preco_compra CHECK (preco_compra >= 0),  -- RN15
    CONSTRAINT ck_produto_preco_venda CHECK (preco_venda >= 0),    -- RN15
    CONSTRAINT ck_produto_estoque_minimo CHECK (estoque_minimo IS NULL OR estoque_minimo >= 0)
);

-- ---------------------------------------------------------------------
-- MOVIMENTACAO  (RF08 a RF11, RF16, RN02, RN03, RN11, RN12)
-- tipo ENTRADA/SAIDA: quantidade > 0.
-- tipo CORRECAO: quantidade = diferença (positiva ou negativa, nunca zero).
-- id_produto fica NULL se o produto for excluído (RN11); por isso a
-- movimentação guarda uma cópia do código e do nome do produto.
-- ---------------------------------------------------------------------
CREATE TABLE movimentacao (
    id_movimentacao  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto       INTEGER,
    id_usuario       INTEGER        NOT NULL,
    tipo             VARCHAR(10)    NOT NULL,
    quantidade       INTEGER        NOT NULL,
    preco_unitario   NUMERIC(10,2),
    saldo_apos       INTEGER        NOT NULL,
    justificativa    VARCHAR(255),
    codigo_produto   VARCHAR(30)    NOT NULL,
    nome_produto     VARCHAR(120)   NOT NULL,
    data_hora        TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mov_produto FOREIGN KEY (id_produto)
        REFERENCES produto (id_produto) ON DELETE SET NULL,
    CONSTRAINT fk_mov_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT ck_mov_tipo CHECK (tipo IN ('ENTRADA', 'SAIDA', 'CORRECAO')),
    CONSTRAINT ck_mov_quantidade CHECK (
        (tipo = 'CORRECAO' AND quantidade <> 0) OR
        (tipo IN ('ENTRADA', 'SAIDA') AND quantidade > 0)),         -- RN09, RN10
    CONSTRAINT ck_mov_preco CHECK (preco_unitario IS NULL OR preco_unitario >= 0),
    CONSTRAINT ck_mov_justificativa CHECK (
        tipo <> 'CORRECAO' OR (justificativa IS NOT NULL AND btrim(justificativa) <> '')) -- RN03
);

-- ---------------------------------------------------------------------
-- LOG_ALTERACAO  (RF17, RN02)
-- id_registro NÃO é chave estrangeira: o registro alterado pode ter sido excluído.
-- ---------------------------------------------------------------------
CREATE TABLE log_alteracao (
    id_log       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario   INTEGER       NOT NULL,
    entidade     VARCHAR(30)   NOT NULL,
    id_registro  INTEGER       NOT NULL,
    acao         VARCHAR(30)   NOT NULL,
    detalhes     VARCHAR(500),
    data_hora    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_log_usuario FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- BACKUP  (RF18, RF19, RN13, RNF03)
-- ---------------------------------------------------------------------
CREATE TABLE backup (
    id_backup      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_hora      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    arquivo        VARCHAR(255)  NOT NULL,
    tamanho_bytes  BIGINT,
    status         VARCHAR(10)   NOT NULL,
    CONSTRAINT ck_backup_status CHECK (status IN ('SUCESSO', 'FALHA')),
    CONSTRAINT ck_backup_tamanho CHECK (tamanho_bytes IS NULL OR tamanho_bytes >= 0)
);

-- ---------------------------------------------------------------------
-- ÍNDICES (pesquisa RF14, painel RF13, histórico RF16)
-- A chave primária e as colunas UNIQUE já têm índice próprio.
-- ---------------------------------------------------------------------
CREATE INDEX idx_produto_nome          ON produto (LOWER(nome));
CREATE INDEX idx_produto_categoria     ON produto (id_categoria);
CREATE INDEX idx_produto_cor           ON produto (LOWER(cor));
CREATE INDEX idx_produto_tamanho       ON produto (LOWER(tamanho));
CREATE INDEX idx_mov_produto           ON movimentacao (id_produto);
CREATE INDEX idx_mov_usuario           ON movimentacao (id_usuario);
CREATE INDEX idx_mov_data_hora         ON movimentacao (data_hora DESC);
CREATE INDEX idx_mov_tipo              ON movimentacao (tipo);
CREATE INDEX idx_log_usuario           ON log_alteracao (id_usuario);
CREATE INDEX idx_log_data_hora         ON log_alteracao (data_hora DESC);
CREATE INDEX idx_backup_data_hora      ON backup (data_hora DESC);

-- ---------------------------------------------------------------------
-- IMUTABILIDADE (RN12, RNF05)
-- Movimentações e logs não podem ser editados nem apagados.
-- Única exceção: o banco zerar movimentacao.id_produto quando o produto é
-- excluído (ON DELETE SET NULL, RN11).
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_bloquear_alteracao_movimentacao() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Movimentações não podem ser apagadas (RN12).';
    END IF;
    -- UPDATE: só é aceito se a única mudança for id_produto virar NULL
    IF NEW.id_produto IS NULL
       AND ROW(NEW.id_movimentacao, NEW.id_usuario, NEW.tipo, NEW.quantidade, NEW.preco_unitario,
               NEW.saldo_apos, NEW.justificativa, NEW.codigo_produto, NEW.nome_produto, NEW.data_hora)
           IS NOT DISTINCT FROM
           ROW(OLD.id_movimentacao, OLD.id_usuario, OLD.tipo, OLD.quantidade, OLD.preco_unitario,
               OLD.saldo_apos, OLD.justificativa, OLD.codigo_produto, OLD.nome_produto, OLD.data_hora)
    THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'Movimentações não podem ser alteradas (RN12). Use uma correção.';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_movimentacao_imutavel
    BEFORE UPDATE OR DELETE ON movimentacao
    FOR EACH ROW EXECUTE FUNCTION fn_bloquear_alteracao_movimentacao();

CREATE FUNCTION fn_bloquear_alteracao_log() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Registros de log não podem ser alterados nem apagados (RNF05).';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_log_imutavel
    BEFORE UPDATE OR DELETE ON log_alteracao
    FOR EACH ROW EXECUTE FUNCTION fn_bloquear_alteracao_log();
